"""Instrumented Cornacchia variants for x^2 + d*y^2 = M (d = 1 in all runs here).

A   classical Cornacchia (Cohen, Alg. 1.5.2 style): Euclid on (M, u) until the
    remainder drops below sqrt(M), then check that the cofactor is a square.
L   unrandomized 2-D Lagrange (Gauss) reduction of the lattice generated by
    (1, u), (0, M)  -- ePrint 2023/807 Sec. 4.2 / Alg. 6, no masking.
B   ePrint 2023/807 Alg. 10 "(Randomized) LatticeReduction(M, d, u)": the basis
    L = [[1, u], [0, M]] is replaced by S*L with S = P_j * R_i * P_j^{-1},
    R_i = [[1, r_i], [0, 1]], r_i a fresh 128-bit random integer and P_j taken
    from a pre-generated list of small-entry unimodular matrices (Sec. 4.2.1),
    then Lagrange-reduced (Alg. 6).
B0  the S = [[1, r0], [r1, r0*r1 + 1]] construction that Sec. 4.2.1 REJECTS
    (kept to reproduce the paper's "always 2 extra iterations" observation).

All arithmetic is plain Python ints (gmpy2 for primality / isqrt). Each function
returns (solution, trace_dict). Nothing here is constant time; it is a model
for counting steps, not an implementation.
"""
import secrets
import gmpy2

R_BITS = 128          # Sec. 4.2: "128-bit uniformly random entries"
P_ENTRY_BITS = 4      # Sec. 4.2.1: P_j entries "much smaller" than 128 bits (our choice;
                      # keeps S entries ~128-145 bits as the paper asks)
P_LIST_LEN = 64       # size of the pre-generated P_j list (our choice)


def bitlen(x):
    return abs(x).bit_length()


# ---------------------------------------------------------------- square root
def sqrt_minus_one(M, rng=secrets):
    """u with u^2 = -1 mod prime M = 1 mod 4. Sec. 4.2: random v, u = v^((M-1)/4),
    retried until v is a non-residue. Returns (u, attempts). u normalised to u < M/2
    so A, L and B all see the same input."""
    attempts = 0
    e = (M - 1) // 4
    while True:
        attempts += 1
        v = 2 + rng.randbelow(M - 3)
        u = pow(v, e, M)
        if (u * u) % M == M - 1:
            return (min(u, M - u), attempts)


# ---------------------------------------------------------------- variant A
def cornacchia_classical(M, u, d=1):
    """Euclid on (M, u) until b < sqrt(M). Trace: steps, quotients."""
    a, b = M, u
    s = gmpy2.isqrt(M)
    q_list = []
    while b > s:                       # data-dependent loop bound
        q, rmd = divmod(a, b)
        q_list.append(q)
        a, b = b, rmd
    rest = M - b * b
    ok = False
    y = None
    if rest % d == 0:
        c = rest // d
        y_ = gmpy2.isqrt(c)
        ok = (y_ * y_ == c)            # cofactor-square check
        y = int(y_) if ok else None
    return ((int(b), y) if ok else None,
            dict(steps=len(q_list), quotients=q_list, square_ok=ok))


# ---------------------------------------------------------------- Alg. 6
def _dot(v, w):
    return v[0] * w[0] + v[1] * w[1]


def _round_div(n, d):
    # nearest integer to n/d, d > 0, ties toward +inf (as floor(n/d + 1/2))
    return (2 * n + d) // (2 * d)


def lagrange_reduce(l0, l1):
    """Alg. 6 (Lagrange/Gauss). Returns (l0, trace). 'steps' counts
    mu-computations (step 2 + every pass of the while loop, steps 5-11)."""
    q_list = []
    swaps = 0
    n0 = _dot(l0, l0)
    if _dot(l1, l1) < n0:
        l0, l1 = l1, l0; n0 = _dot(l0, l0); swaps += 1
    mu = _round_div(_dot(l0, l1), n0)
    q_list.append(mu)
    l1 = (l1[0] - mu * l0[0], l1[1] - mu * l0[1])
    while _dot(l1, l1) < n0:
        l0, l1 = l1, l0
        swaps += 1
        n0 = _dot(l0, l0)
        mu = _round_div(_dot(l0, l1), n0)
        q_list.append(mu)
        l1 = (l1[0] - mu * l0[0], l1[1] - mu * l0[1])
    return l0, dict(steps=len(q_list), quotients=q_list, swaps=swaps)


def _solution_from(v, M, d=1):
    x, y = abs(v[0]), abs(v[1])
    return (x, y) if x * x + d * y * y == M else None


# ---------------------------------------------------------------- variant L
def lattice_plain(M, u):
    l0, tr = lagrange_reduce((1, u), (0, M))
    sol = _solution_from(l0, M)
    tr['square_ok'] = sol is not None
    return sol, tr


# ---------------------------------------------------------------- S generation
def _mat_mul(A, B):
    return ((A[0][0]*B[0][0] + A[0][1]*B[1][0], A[0][0]*B[0][1] + A[0][1]*B[1][1]),
            (A[1][0]*B[0][0] + A[1][1]*B[1][0], A[1][0]*B[0][1] + A[1][1]*B[1][1]))


def _inv_unimod(A):
    (a, b), (c, d) = A
    det = a * d - b * c
    assert det in (1, -1)
    return ((d * det, -b * det), (-c * det, a * det))


def random_small_unimodular(bits=P_ENTRY_BITS, rng=secrets):
    """Random det-1 matrix with entries < 2^bits, non-identity: pick coprime
    (a, c) and solve a*d - b*c = 1 (b, d reduced mod a, c)."""
    while True:
        a = rng.randbelow(1 << bits) + 1
        c = rng.randbelow(1 << bits) + 1
        g, s, t = gmpy2.gcdext(a, c)
        if g != 1:
            continue
        # a*s + c*t = 1  ->  d = s, b = -t
        P = ((a, int(-t)), (c, int(s)))
        if P != ((1, 0), (0, 1)):
            return P


class SGenerator:
    """Sec. 4.2.1: S_ij = P_j R_i P_j^{-1}; list of pre-generated P_j; when the
    list is exhausted (i > j) new P_t = P_j * P_j' (random product)."""
    def __init__(self, list_len=P_LIST_LEN, rng=secrets):
        self.rng = rng
        self.base = [random_small_unimodular(rng=rng) for _ in range(list_len)]
        self.P = list(self.base)
        self.i = 0

    def next(self):
        r = self.rng.randbits(R_BITS) | (1 << (R_BITS - 1))   # full 128-bit
        if self.rng.randbelow(2):
            r = -r
        R = ((1, r), (0, 1))
        if self.i < len(self.P):
            P = self.P[self.i]
        else:
            # products of two *base* matrices only, so entries stay small
            P = _mat_mul(self.base[self.rng.randbelow(len(self.base))],
                         self.base[self.rng.randbelow(len(self.base))])
        self.i += 1
        S = _mat_mul(_mat_mul(P, R), _inv_unimod(P))
        return S


def naive_S(rng=secrets):
    r0 = rng.randbits(R_BITS) | (1 << (R_BITS - 1))
    r1 = rng.randbits(R_BITS) | (1 << (R_BITS - 1))
    return ((1, r0), (r1, r0 * r1 + 1))


# ---------------------------------------------------------------- variant B
def lattice_randomized(M, u, S):
    L = ((1, u), (0, M))
    SL = _mat_mul(S, L)                       # Alg. 10 step 3: L <- S * L
    l0, tr = lagrange_reduce(SL[0], SL[1])    # Alg. 10 step 4
    sol = _solution_from(l0, M)
    tr['square_ok'] = sol is not None
    tr['S_maxbits'] = max(bitlen(e) for row in S for e in row)
    return sol, tr
