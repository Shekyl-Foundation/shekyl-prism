"""Every lattice L with m Z^4 <= L <= Z^4 for small m (not only ideals), random generating sets.

Exhaustive over all dev-convention HNFs with pivots dividing m for m = 2, 3, 4; random sample
for larger composite and prime-power m (including m with a 2-part and squares).  Each lattice is
generated by 4..6 scrambled rows and run at K = bitlen(m) and bitlen(m)+2.  The result must equal the
constructed HNF (ground truth by construction); PARI is consulted on a sample.
Also: generators that do NOT contain m Z^4 -- the output must be HNF(span G + m Z^4).
"""
import itertools, random, sys, time
from math import gcd
import lib
from fmhnf import fixed_modulus_hnf


def divisors(m):
    return [d for d in range(1, m + 1) if m % d == 0]


def all_hnfs(m):
    ds = divisors(m)
    for d in itertools.product(ds, repeat=4):          # d[c] = pivot of column c
        ranges = []
        for c in range(4):
            for l in range(c):
                ranges.append((c, l, d[l]))
        for vals in itertools.product(*[range(r[2]) for r in ranges]):
            cols = [[0] * (c + 1) for c in range(4)]
            for c in range(4):
                cols[c][c] = d[c]
            for (c, l, _), v in zip(ranges, vals):
                cols[c][l] = v
            yield cols


def rand_hnf(rng, m):
    ds = divisors(m)
    d = [rng.choice(ds) for _ in range(4)]
    cols = [[0] * (c + 1) for c in range(4)]
    for c in range(4):
        cols[c][c] = d[c]
        for l in range(c):
            cols[c][l] = rng.randrange(d[l])
    return cols


def contains_mZ4(cols, m):
    for c in range(4):
        e = [0] * 4
        e[c] = m
        if not lib.lattice_contains(cols, e):
            return False
    return True


def run_lattice(rng, cols, m, K, stats, pari_every):
    k = rng.choice((4, 5, 6))
    G = lib.scramble(rng, cols, k, rng.choice((2, 5, K)), 1 << (2 * K))
    P, ctx = fixed_modulus_hnf(G, m, K)
    assert P == cols, (m, K, cols, G, P)
    stats['runs'] += 1
    stats['hash'].add((k, ctx.trace_hash()))
    if stats['runs'] % pari_every == 0:
        assert lib.pari_hnf_cols(G, m) == P
        stats['pari'] += 1


def main(skip_lattices=False):
    rng = random.Random(11)
    stats = dict(runs=0, pari=0, hash=set(), lattices=0, nonspan=0)
    t0 = time.time()
    for m in (() if skip_lattices else (2, 3, 4)):
        n = 0
        for cols in all_hnfs(m):
            if not contains_mZ4(cols, m):
                continue
            n += 1
            for K in (m.bit_length(), m.bit_length() + 2):
                run_lattice(rng, cols, m, K, stats, 97)
        stats['lattices'] += n
        print('m=%d: all %d lattices containing mZ^4, 2 K values each' % (m, n)); sys.stdout.flush()
    for m, cnt in (() if skip_lattices else ((5, 2000), (6, 4000), (8, 3000), (9, 3000), (10, 2000), (12, 3000), (16, 2000), (18, 2000),
                   (30, 1500), (36, 1500), (64, 1000), (210, 800), (1024, 400), (2 * 3 * 5 * 7 * 11 * 13, 400))):
        got = 0
        tries = 0
        while got < cnt and tries < 400 * cnt:
            tries += 1
            cols = rand_hnf(rng, m)
            if not contains_mZ4(cols, m):
                continue
            got += 1
            for K in (m.bit_length(), m.bit_length() + 2):
                run_lattice(rng, cols, m, K, stats, 53)
        stats['lattices'] += got
        print('m=%d: %d random lattices containing mZ^4 (of %d tried)' % (m, got, tries)); sys.stdout.flush()
    # generators not containing m Z^4: output is HNF(span G + m Z^4)
    for m in (4, 6, 12, 30, 2 * 509):
        for _ in range(600):
            K = m.bit_length() + rng.choice((0, 1, 5))
            k = rng.choice((1, 2, 3, 4, 6))
            G = [[rng.randrange(-(1 << (2 * K)) + 1, 1 << (2 * K)) for _ in range(4)] for _ in range(k)]
            if rng.random() < 0.5:
                G = [[(x * c if abs(x * c) < (1 << (2 * K)) else x) if rng.random() < .5 else 0
                      for x, c in ((x, rng.choice((1, 2, 3))) for x in r)] for r in G]
            P, ctx = fixed_modulus_hnf(G, m, K)
            assert P == lib.pari_hnf_cols(G, m) == lib.sage_hnf_cols(G, m)
            stats['nonspan'] += 1
    print('generators without 2N Z^4 inside: %d cases equal HNF(span G + mZ^4)' % stats['nonspan'])
    print('TOTAL: %d lattices, %d runs (PARI cross-check on %d), %d distinct (k, trace) classes, %.0fs' %
          (stats['lattices'], stats['runs'], stats['pari'], len(stats['hash']), time.time() - t0))
    # trace identity: one hash per (k, K); here K varies, so check count of hashes = distinct (k, K) pairs
    return stats


if __name__ == '__main__':
    main(skip_lattices='--nonspan-only' in sys.argv)
