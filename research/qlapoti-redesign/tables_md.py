"""results/tables.json (analyze.py) + c_o29/runs (run_c.py) ->
results/TABLES.md. Every figure is a model estimate unless it is a count
from the C reference runs."""
import glob
import json
from collections import defaultdict
from pathlib import Path

from costmodel import SetCost, REF_MEAN_WORK, PRIOR

HERE = Path(__file__).resolve().parent
T = json.load(open(HERE / 'results' / 'tables.json'))
SETS = [s for s in ['p500', 'p248', 'p324', 'p376', 'p664'] if s in T]
L = []
w = L.append


def f1(x):
    return f'{x:.1f}' if x < 100 else f'{x:.0f}'


def best(dd, pred):
    c = [(k, v) for k, v in dd.items() if pred(k) and v]
    return min(c, key=lambda kv: kv[1]['W'])


w('# qlapoti redesign: tables (model estimates)')
w('')
w('Generated by `tables_md.py` from `results/tables.json` (`analyze.py`) and')
w('`c_o29/runs/` (`run_c.py`). Padding factors are fixed-schedule work divided')
w('by the reference mean work at e-2 (prior experiment T8, fne model):')
w(', '.join(f'{s} {REF_MEAN_WORK[s]:,.0f}' for s in SETS) + '.')
w('All work figures are **model estimates** (fsne-compatible work units, not')
w('cycles), sized for the worst prepared ideal (u = n/sqrt(p) -> 1/sqrt(2)).')
w('M4 is sized from a public n_min 34 bits below the Hermite bound.')
w('')

# --- T1 population
w('## T1 Population (600 prepared ideals S per set)')
w('')
w('| set | even n | u min | u median | u max | gen. validity worst / mean | max draws seen |')
w('|---|---|---|---|---|---|---|')
for s in SETS:
    t = T[s]
    c = t['caps']
    w(f"| {s} | {t['even_share']:.3f} | {t['u_min']:.3f} | {t['u_med']:.3f} | {t['u_max']:.3f} | "
      f"{c['gen_v'][0]:.3f} / {c['gen_v'][1]:.3f} | {c['gen_max']} |")
w('')

# --- T2 per-lambda outcomes
w('## T2 Reference structure: per-lambda outcome fractions (all S, 8 generators x 4000 lambda)')
w('')
w('| set | de | noncoprime | m<0 | M4<=0 | mod | prime/Corn. | post-fail | success | success per coprime | post rejects | dead generators | worst-u scale | rate at u=1/sqrt2 |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for s in SETS:
    for de in ('2', '1', '0'):
        R = T[s]['de'][de]
        w(f"| {s} | e-{de} | {R['frac0']:.3f} | {R['frac1']:.4f} | {R['frac2']:.3f} | {R['frac3']:.3f} | "
          f"{R['frac4']:.3f} | {R['frac5']:.4f} | {R['frac6']:.5f} | {R['rate_cop']:.5f} | {R['post_reject']:.3f} | "
          f"{R['dead_gen']:.3f} | {R['scale']:.2f} | {R['worst_rate_int']:.6f} |")
w('')
w('"dead generators": share of (S, generator) pairs whose every Cornacchia')
w('success fails the postcondition. "worst-u scale": factor from the top')
w('u-decile pooled rate to u = 1/sqrt(2) (power law on the upper half).')
w('')

# --- T3 caps
w('## T3 Sub-experiment 1: inner-loop completion vs cap')
w('')
w('Generator draws (per call, all S pooled; 64 calls per S):')
w('')
caps = [1, 2, 4, 8, 13, 16, 24, 32, 48, 64]
w('| set | ' + ' | '.join(f'K<={k}' for k in caps) + ' | max |')
w('|---|' + '---|' * (len(caps) + 1))
for s in SETS:
    c = T[s]['caps']
    w(f'| {s} | ' + ' | '.join(f"{c['gen'][str(k)]:.4f}" for k in caps) + f" | {c['gen_max']} |")
w('')
w('Coprime-lambda skip (share of skip-loop invocations that find a coprime')
w('lambda within C+1 candidates; pooled / worst S):')
w('')
Cs = ['0', '1', '2', '3', '4', '6', '8']
w('| set | ' + ' | '.join(f'C={c}' for c in Cs) + ' |')
w('|---|' + '---|' * len(Cs))
for s in SETS:
    c = T[s]['caps']['skip']
    w(f'| {s} | ' + ' | '.join(f'{c[k][0]:.4f} / {c[k][1]:.3f}' for k in Cs) + ' |')
w('')
w('2-D Gauss steps and Cornacchia Euclid steps (observed maxima vs the fixed')
w('caps of the cost model, T_lat = ceil(0.3932 nb)+3, T_corn = ceil(0.7202 mb)+3):')
w('')
w('| set | Gauss max / mean | T_lat | Euclid max (e-2 / e) | T_corn (e-2 / e) |')
w('|---|---|---|---|---|')
for s in SETS:
    c = T[s]['caps']
    a, b = SetCost(s, 2), SetCost(s, 0)
    w(f"| {s} | {c['gauss']['max']} / {c['gauss']['mean']:.1f} | {a.T_lat} | "
      f"{c['corn']['2']['max']} / {c['corn']['0']['max']} | {a.T_corn} / {b.T_corn} |")
w('')

# --- T4 designs on the reference structure
w('## T4 Fixed-schedule designs on the reference structure (padding factor, 99.9% / 2^-64)')
w('')
w('`skipC`: generator pool + blocks of M slots, each slot the first coprime')
w('lambda among C+1, every slot runs the expensive stage. `prime`: public')
w('prime-lambda list. `2st`: prime list + sieve below 2^K + oblivious')
w('compaction + Q expensive slots. Prior: the earlier experiment\'s "fresh"')
w('design (n_min 8 bits below the bound).')
w('')
w('| set | de | prior | best skipC (C, M) | prime (M) | best two-stage (K, M, P, Q) |')
w('|---|---|---|---|---|---|')
for s in SETS:
    for de in ('2', '1', '0'):
        D = T[s]['de'][de]['designs']
        row = []
        for lab in ('99.9%', '2^-64'):
            dd = D[lab]
            k, v = best(dd, lambda k: k.startswith('skip'))
            p = dd['prime']
            k2, v2 = best(dd, lambda k: k.startswith('2st'))
            row.append((f"{f1(v['factor'])} ({k[4:]}, {v['M']})", f"{f1(p['factor'])} ({p['M']})",
                        f"{f1(v2['factor'])} ({v2['Ksv']}, {v2['M']}, {v2['P']}, {v2['Q']})"))
        pr = f'{PRIOR[s][0]} / {PRIOR[s][1]}' if de == '2' else '-'
        w(f'| {s} | e-{de} | {pr} | {row[0][0]} / {row[1][0]} | {row[0][1]} / {row[1][1]} | '
          f'{row[0][2]} / {row[1][2]} |')
w('')

# --- T5 Qlapoty-style
w('## T5 Qlapoty-style prototype (odd n only; padding factor, 99.9% / 2^-64)')
w('')
w('Balanced alpha0 (Loop1-lite), odd lambda, mod-4n lattice, z prime = 1 mod 4.')
w('Variants: p = prime z only with the PRISM_v2 postcondition; pe = extended')
w('Cornacchia (good primes stripped) with postcondition; pn / pen = the same')
w('without the postcondition (needs a chain that accepts every theta, see O29).')
w('Best of one-stage / two-stage (sieve K, skip C=1) per variant.')
w('')
w('| set | de | odd share | z<=0 | post rejects | p | pe | pn | pen |')
w('|---|---|---|---|---|---|---|---|---|')
for s in SETS:
    Q = T[s].get('qlapoty')
    if not Q:
        continue
    for de in ('2', '1', '0'):
        R = Q['de'][de]
        cells = []
        for v in ('p', 'pe', 'pn', 'pen'):
            a = best(R['designs']['99.9%'], lambda k: k.startswith(v + '_'))[1]['factor']
            b = best(R['designs']['2^-64'], lambda k: k.startswith(v + '_'))[1]['factor']
            cells.append(f'{f1(a)} / {f1(b)}')
        w(f"| {s} | e-{de} | {Q['odd_share']:.3f} | {R['frac2']:.3f} | {R['post_reject']:.3f} | " + ' | '.join(cells) + ' |')
w('')
w('Loop1-lite iterations per alpha0 (prototype; the cap is 2000):')
w('')
w('| set | mean | <=8 | <=16 | <=64 | stuck ideals (every draw hit the cap) |')
w('|---|---|---|---|---|---|')
for s in SETS:
    Q = T[s].get('qlapoty')
    if Q:
        l1 = Q['loop1']
        w(f"| {s} | {l1['mean']:.1f} | {l1['cdf']['8']:.3f} | {l1['cdf']['16']:.3f} | {l1['cdf']['64']:.3f} | "
          f"{Q['loop1_stuck_S']} / {Q['loop1_S']} |")
w('')

# --- T6 C runs
runs = defaultdict(list)
for fn in glob.glob(str(HERE / 'c_o29' / 'runs' / '*.jsonl')):
    for line in open(fn):
        d = json.loads(line)
        runs[(d['var'], d['lvl'])].append(d)
if runs:
    w('## T6 O29 against the C reference (counts, not estimates)')
    w('')
    w('PRISM_v2 @ 87fad7d + QLSTAT patch, Debug -O2 with asserts. Variants:')
    w('e2 = pin (used power e-2), e1, e0 = used power e; e2np / e0np = the')
    w('postcondition disabled (every theta accepted). One keygen + one sign +')
    w('open per seed. "pk = pin": public key bytes equal to the e2 run with')
    w('the same seed; "sm = pin": signed message bytes equal.')
    w('')
    w('| variant | lvl | runs | keygen ok | sign ok | verify ok | chain warnings before verify | pk = pin | sm = pin | mean passes (keygen, sign) |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    for var in ('e2', 'e1', 'e0', 'e2np', 'e0np'):
        for lvl in (1, 3, 5):
            rs = runs.get((var, lvl))
            if not rs:
                continue
            base = {d['seed']: d for d in runs.get(('e2', lvl), [])}
            n = len(rs)
            kg = sum(bool(d.get('keygen_ok')) for d in rs)
            sg = sum(bool(d.get('sign_ok')) for d in rs)
            vf = sum(bool(d.get('verify_ok')) for d in rs)
            wn = sum(1 for d in rs if d.get('warn_pre'))
            pk = sum(1 for d in rs if d['seed'] in base and d.get('pk') and d.get('pk') == base[d['seed']].get('pk'))
            sm = sum(1 for d in rs if d['seed'] in base and d.get('sm') and d.get('sm') == base[d['seed']].get('sm'))
            ps = [int(q.split()[0]) for d in rs for q in d.get('qlstat', [])]
            mp = sum(ps) / len(ps) if ps else 0
            w(f'| {var} | {lvl} | {n} | {kg} | {sg} | {vf} | {wn} | {pk} | {sm} | {mp:.0f} |')
    w('')

(HERE / 'results' / 'TABLES.md').write_text('\n'.join(L) + '\n')
print('\n'.join(L))
