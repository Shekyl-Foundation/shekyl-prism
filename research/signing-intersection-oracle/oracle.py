"""Independent exact-integer oracle for the specialized signing intersection.

Written from the mathematics and the public spec text only. It imports nothing
from the Rust prototype or from the research scripts' intersection or reduction
routines. Lattice work is done by Sage (row HNF, submodule intersection) and PARI
(mathnf, used for the dual-lattice route).

Conventions
  B_{p,oo} = (-1,-p | Q), p = 3 mod 4 prime, i^2 = -1, j^2 = -p, k = ij.
  O0 = <1, i, (i+j)/2, (1+k)/2>.  An element x is carried by its numerator
  X = 2x = (a,b,c,d) in Z^4.  O0 numerators: a = d, b = c (mod 2).
  Left multiplication by i is J(a,b,c,d) = (-b,a,-d,c).  With alpha = a+bi,
  beta = c+di this is (alpha,beta) -> (i alpha, i beta): Z[i]-module Z[i]^2.
"""
from sage.all import ZZ, QQ, matrix, vector, Mod, is_prime, gcd, isqrt
from cypari2 import Pari

_pari = Pari()
_pari.allocatemem(2 * 10**9, silent=True)

# ---------------------------------------------------------------- quaternions

def qmul_int(p, A, B):
    """Product of integer-coordinate quaternions (basis 1,i,j,k)."""
    a0, a1, a2, a3 = A
    b0, b1, b2, b3 = B
    return (
        a0 * b0 - a1 * b1 - p * a2 * b2 - p * a3 * b3,
        a0 * b1 + a1 * b0 + p * a2 * b3 - p * a3 * b2,
        a0 * b2 + a2 * b0 + a3 * b1 - a1 * b3,
        a0 * b3 + a3 * b0 + a1 * b2 - a2 * b1,
    )

def qmul(p, X, Y):
    """Numerator of the product of the elements with numerators X and Y."""
    Z = qmul_int(p, X, Y)
    assert all(z % 2 == 0 for z in Z), "product numerator not integral"
    return tuple(z // 2 for z in Z)

O0 = ((2, 0, 0, 0), (0, 2, 0, 0), (0, 1, 1, 0), (1, 0, 0, 1))

def in_O0(X):
    return (X[0] - X[3]) % 2 == 0 and (X[1] - X[2]) % 2 == 0

def J(X):
    return (-X[1], X[0], -X[3], X[2])

def D(p, X, Y):
    """Hermitian-form real part: 4 * reduced-norm polarisation."""
    return X[0] * Y[0] + X[1] * Y[1] + p * (X[2] * Y[2] + X[3] * Y[3])

def N4(p, X):
    return D(p, X, X)

# ------------------------------------------------------------------- lattices
# A lattice is its canonical row HNF (tuple of 4 tuples), full rank.

def hnf_rows(rows):
    M = matrix(ZZ, [list(r) for r in rows]).echelon_form()
    out = tuple(tuple(int(x) for x in M.row(i)) for i in range(M.nrows()) if any(M.row(i)))
    return out

def lat_index(H):
    d = 1
    for i, r in enumerate(H):
        d *= r[i]
    return d

def lat_contains(H, w):
    w = list(w)
    for i, r in enumerate(H):
        if w[i] % r[i]:
            return False
        c = w[i] // r[i]
        w = [a - c * b for a, b in zip(w, r)]
    return not any(w)

def lat_subset(H1, H2):
    return all(lat_contains(H2, r) for r in H1)

def ideal_from_gens(p, gens):
    """Left O0-ideal generated by numerators `gens`: Z-span of g*w."""
    rows = [qmul(p, e, w) for e in O0 for w in gens]
    return hnf_rows(rows)

def is_left_O0_ideal(p, H):
    if len(H) != 4:
        return False
    if not all(in_O0(r) for r in H):
        return False
    return all(lat_contains(H, qmul(p, e, r)) for e in O0 for r in H)

L0 = hnf_rows(O0)          # index 4 in Z^4
assert lat_index(L0) == 4

def ideal_norm(H):
    """Reduced norm of an integral ideal = sqrt of its index in O0."""
    idx = lat_index(H) // lat_index(L0)
    assert lat_index(H) % lat_index(L0) == 0
    n = isqrt(idx)
    assert n * n == idx
    return n

def gaussian_span(u, v):
    """Z-lattice spanned by u, Ju, v, Jv."""
    return hnf_rows([u, J(u), v, J(v)])

# --- three independent lattice-intersection engines -------------------------

def inter_sage(H1, H2):
    M1 = (ZZ ** 4).submodule([list(r) for r in H1])
    M2 = (ZZ ** 4).submodule([list(r) for r in H2])
    I = M1.intersection(M2)
    return hnf_rows([list(map(int, b)) for b in I.basis()])

def inter_pari_dual(H1, H2):
    """L1 ∩ L2 = (L1* + L2*)*, rational dual lattices, PARI mathnf."""
    def dual(H):
        return matrix(QQ, [list(r) for r in H]).inverse().transpose()
    D1, D2 = dual(H1), dual(H2)
    rows = [list(D1.row(i)) for i in range(4)] + [list(D2.row(i)) for i in range(4)]
    den = 1
    for r in rows:
        for x in r:
            den = den * x.denominator() // gcd(den, x.denominator())
    Z = [[int(x * den) for x in r] for r in rows]
    # mathnf works on columns: generators are the columns of the transpose
    cols = _pari.matrix(4, 8, [Z[j][i] for i in range(4) for j in range(8)])
    Hn = _pari.mathnf(cols)  # 4x4, columns = basis of the sum of the duals, scaled by den
    S = matrix(QQ, [[int(Hn[i, j]) for i in range(4)] for j in range(4)]) / den  # rows
    Dd = S.inverse().transpose()
    den2 = 1
    for i in range(4):
        for x in Dd.row(i):
            den2 = den2 * x.denominator() // gcd(den2, x.denominator())
    assert den2 == 1, "intersection of integral lattices is integral"
    return hnf_rows([[int(x) for x in Dd.row(i)] for i in range(4)])

def inter_kernel_residue(p, Hs, q, root):
    """{w in I_s : rho_r(w) = 0 mod q}, by linear algebra over Z, no coprimality used.
    Hs: HNF rows of I_s.  The map is the Z[i]-linear residue
    rho(a,b,c,d) = (a - c x + d y, b - c y - d x) mod q."""
    x, y = root
    rows = []
    for r in Hs:
        a, b, c, d = r
        rows.append(((a - c * x + d * y) % q, (b - c * y - d * x) % q))
    # lattice of coefficient vectors m in Z^4 with sum m_i rows_i = 0 mod q (componentwise)
    # = kernel of [R | q I_2] projected to first 4 coordinates
    M = matrix(ZZ, 6, 4 + 2, 0)
    for i in range(4):
        M[i, i] = 1
        M[i, 4] = rows[i][0]
        M[i, 5] = rows[i][1]
    M[4, 4] = q
    M[5, 5] = q
    # integer left kernel of the 6x2 block [rows; q I] gives coefficients (m, t) with m R + t q = 0
    B = matrix(ZZ, [[rows[i][0], rows[i][1]] for i in range(4)] + [[q, 0], [0, q]])
    K = B.left_kernel().basis_matrix()   # rows (m0..m3, t0, t1)
    coeffs = [list(map(int, K.row(i)))[:4] for i in range(K.nrows())]
    vecs = [[sum(c[i] * Hs[i][k] for i in range(4)) for k in range(4)] for c in coeffs]
    return hnf_rows(vecs)

# ------------------------------------------------------------- ideal builders

def ideal_root(p, N, root):
    """O0*N + O0*(x + y i + j): numerators (2N,0,0,0) and (x,y,1,0)."""
    x, y = root
    return ideal_from_gens(p, [(2 * N, 0, 0, 0), (x, y, 1, 0)])

def generic_hnf_columns(N, root):
    """The column matrix Rick's prototype calls GenericHnf (as given in the spec):
    (2N,0,0,0), (0,2N,0,0), (x,y,1,0), (2N-y, x, 0, 1).  Returned as rows (transposed)
    in the row-HNF layout used here: row k is column k."""
    x, y = root
    return ((2 * N, 0, 0, 0), (0, 2 * N, 0, 0), (x, y, 1, 0), (2 * N - y, x, 0, 1))

def is_canonical_hnf_shape(cols):
    """Column-HNF in the prototype's layout: column j has zeros below row j,
    positive pivot, entries above pivot in [0, pivot_i)."""
    for j, col in enumerate(cols):
        if col[j] <= 0:
            return False
        for i, xv in enumerate(col):
            if i > j and xv != 0:
                return False
            if i < j and not (0 <= xv < cols[i][i]):
                return False
    return True

# canonical *column* HNF layout: our row HNF is of the transposed convention.
# For a column HNF (lower entries zero) take the row-HNF of reversed coordinates? Rather than
# convert, compare lattices: columns of the prototype layout are vectors; the lattice they span
# is hnf_rows(cols).  Upper-triangular-column shape is checked by is_canonical_hnf_shape.

# ------------------------------------------------------- Gaussian reduction

def half_up_div(a, b):
    """floor(a/b + 1/2) for b > 0."""
    return (2 * a + b) // (2 * b)

def lagrange(p, u, v, trace=False):
    """Exact Z[i] Lagrange reduction under the rules in SIGNER_SPEC 2.3:
    initial swap iff N4(V) < N4(U); step: m_j = floor(h_j/A + 1/2), V -= m0 U + m1 JU,
    swap iff new N4(V) < A (strict). Returns (u, v, active_steps, swaps)."""
    if N4(p, v) < N4(p, u):
        u, v = v, u
    steps = swaps = 0
    while True:
        A = N4(p, u)
        h0 = D(p, v, u)
        h1 = D(p, v, J(u))
        m0, m1 = half_up_div(h0, A), half_up_div(h1, A)
        ju = J(u)
        nv = tuple(v[k] - m0 * u[k] - m1 * ju[k] for k in range(4))
        steps += 1
        if N4(p, nv) < A:
            u, v = nv, u
            swaps += 1
            continue
        if m0 == 0 and m1 == 0:
            return u, v, steps, swaps
        v = nv

def norm_gram(p, T, u, v):
    """(A', C', h0', h1') = (N4U, N4V, D(V,U), D(V,JU)) / (2T), or None if inexact."""
    vals = (N4(p, u), N4(p, v), D(p, v, u), D(p, v, J(u)))
    if any(x % (2 * T) for x in vals):
        return None
    return tuple(x // (2 * T) for x in vals)

def gram_det(p, g):
    A, C, h0, h1 = g
    return A * C - h0 * h0 - h1 * h1

def generic_gram(p, T, root):
    """(2T, (x^2+y^2+p)/(2T), x, y) for U=(2T,0,0,0), V=(x,y,1,0)."""
    x, y = root
    s = x * x + y * y + p
    if s % (2 * T):
        return None
    return (2 * T, s // (2 * T), x, y)

# -------------------------------------------- specialised construction (spec)

def center(z, q):
    return z - q if z > (q >> 1) else z

def rho(w, root, q):
    x, y = root
    a, b, c, d = w
    return ((a - c * x + d * y) % q, (b - c * y - d * x) % q)

def spec_intersection(p, N, u, v, q, root, fermat=True):
    """Re-implementation of the specialised signing intersection from its description:
    U = q v, V = u + gamma v (+ gamma_1 Jv), gamma = -(rho(u) conj rho(v)) / N(rho(v)) mod q,
    centred componentwise. Returns (U, V, T) or None when the checks mark the output."""
    if (root[0] ** 2 + root[1] ** 2 + p) % q:
        return None
    ru, rv = rho(u, root, q), rho(v, root, q)
    nrm = (rv[0] ** 2 + rv[1] ** 2) % q
    inv = pow(nrm, q - 2, q) if fermat else (pow(nrm, -1, q) if gcd(nrm, q) == 1 else 0)
    if (inv * nrm) % q != 1 % q:
        return None
    re = ru[0] * rv[0] + ru[1] * rv[1]
    im = ru[1] * rv[0] - ru[0] * rv[1]
    g = tuple(-center((t * inv) % q, q) for t in (re, im))
    jv = J(v)
    V = tuple(u[k] + g[0] * v[k] + g[1] * jv[k] for k in range(4))
    U = tuple(q * x for x in v)
    return U, V, N * q

# ---------------------------------------------------- general constructions

def general_constructions(p, N, root_s, q, root_q, Hs=None):
    """Return dict of lattices (row HNFs) for I_s ∩ I_q by independent routes.
    I_s = O0 N + O0 (x+yi+j), I_q likewise, built by left-closure, not from any shape."""
    Hs = Hs if Hs is not None else ideal_root(p, N, root_s)
    Hq = ideal_root(p, q, root_q)
    out = {"Hs": Hs, "Hq": Hq}
    out["sage"] = inter_sage(Hs, Hq)
    out["pari_dual"] = inter_pari_dual(Hs, Hq)
    out["kernel"] = inter_kernel_residue(p, Hs, q, root_q)
    # Q3 (coprime norms): q I_s + N I_q
    out["q3"] = hnf_rows([tuple(q * x for x in r) for r in Hs] + [tuple(N * x for x in r) for r in Hq])
    return out

def crt_root(N, root_s, q, root_q):
    """Root of the intersection ideal of norm T = N q, parity-lifted (x even, y odd, in [0,2T))."""
    T = N * q
    from sage.all import crt
    x = int(crt(root_s[0] % N, root_q[0] % q, N, q))
    y = int(crt(root_s[1] % N, root_q[1] % q, N, q))
    x += (x % 2) * T
    y += (1 - y % 2) * T
    return (x, y)

def gaussian_basis_of(H):
    """A Z[i]-basis (u, v) of a left O0-ideal lattice H (rank 2 over Z[i]) by Gaussian-Euclidean
    elimination on (alpha, beta) in Z[i]^2. Returns numerators (u, v) with
    u = (alpha1, beta1), v = (0, beta2)."""
    # elements as (alpha, beta) with alpha=(a,b), beta=(c,d) Gaussian integers (pairs)
    def gmul(x, y):
        return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])
    def gsub(x, y):
        return (x[0] - y[0], x[1] - y[1])
    def gdivround(x, y):
        n = y[0] * y[0] + y[1] * y[1]
        # x * conj(y) / n
        re = x[0] * y[0] + x[1] * y[1]
        im = x[1] * y[0] - x[0] * y[1]
        return (half_up_div(re, n), half_up_div(im, n))
    def gzero(x):
        return x == (0, 0)
    vecs = [((r[0], r[1]), (r[2], r[3])) for r in H]
    # eliminate alpha
    while True:
        nz = [w for w in vecs if not gzero(w[0])]
        if len(nz) <= 1:
            break
        nz.sort(key=lambda w: w[0][0] ** 2 + w[0][1] ** 2)
        piv = nz[0]
        new = [piv]
        for w in vecs:
            if w is piv:
                continue
            if gzero(w[0]):
                new.append(w)
                continue
            m = gdivround(w[0], piv[0])
            mb = gmul(m, piv[1])
            ma = gmul(m, piv[0])
            new.append((gsub(w[0], ma), gsub(w[1], mb)))
        vecs = new
    piv = [w for w in vecs if not gzero(w[0])]
    rest = [w for w in vecs if gzero(w[0])]
    assert len(piv) == 1
    # gcd of the betas in rest (they are all multiples of a gaussian gcd)
    g = (0, 0)
    for w in rest:
        b = w[1]
        if gzero(b):
            continue
        if gzero(g):
            g = b
            continue
        x, y = g, b
        while not gzero(y):
            m = gdivround(x, y)
            x, y = y, gsub(x, gmul(m, y))
        g = x
    P = piv[0]
    u = (P[0][0], P[0][1], P[1][0], P[1][1])
    v = (0, 0, g[0], g[1])
    return u, v
