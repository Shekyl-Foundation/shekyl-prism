"""Refuse an AI-attribution trailer in the commits a push or PR introduces.

The range is `merge-base(base, head)..head`. History already on the base is
not re-tried: the commit that carried `Co-authored-by: Cursor` is on `dev`,
and this gate exists so the next one does not land. An empty range fails.
Scanning nothing is not a pass.
"""

import argparse
import re
import subprocess
import sys

TOOL = re.compile(
    r"\b(cursor|claude|copilot|cody|chatgpt|openai|anthropic|gemini)\b",
    re.IGNORECASE,
)
TRAILER = re.compile(
    r"^(co-authored-by|signed-off-by|helped-by|made-with|made with)\s*:",
    re.IGNORECASE,
)
GENERATED = re.compile(r"^(generated|assisted) by\b", re.IGNORECASE)


def offending(message: str) -> list[str]:
    hits = []
    for raw in message.splitlines():
        line = raw.strip()
        attributed = TOOL.search(line) is not None
        if attributed and (TRAILER.match(line) or GENERATED.match(line)):
            hits.append(line)
    return hits


def commits(base: str, head: str) -> list[tuple[str, str]]:
    if not base or set(base) <= {"0"}:
        raise SystemExit("no base commit; refusing to scan an unnamed range")
    merge_base = subprocess.run(
        ["git", "merge-base", base, head],
        check=False,
        capture_output=True,
        text=True,
    )
    if merge_base.returncode != 0:
        raise SystemExit(merge_base.stderr.strip() or "merge-base failed")
    log = subprocess.run(
        ["git", "log", "--format=%H%x00%B%x00", f"{merge_base.stdout.strip()}..{head}"],
        check=False,
        capture_output=True,
    )
    if log.returncode != 0:
        raise SystemExit(log.stderr.decode().strip() or "git log failed")
    parts = log.stdout.split(b"\x00")
    found = []
    index = 0
    while index + 1 < len(parts):
        sha = parts[index].decode()
        body = parts[index + 1].decode()
        if sha:
            found.append((sha, body))
        index += 2
    if not found:
        raise SystemExit(f"no commit in {base}..{head}")
    return found


def selftest() -> int:
    samples = {
        "Co-authored-by: Ada Lovelace <ada@example.com>\n": False,
        "Co-authored-by: Cursor <cursoragent@cursor.com>\n": True,
        "Generated by the exporter.\n": False,
        "Generated by Claude.\n": True,
        "Made-with: Copilot\n": True,
        "Assisted by Cody.\n": True,
    }
    for message, bad in samples.items():
        hits = offending(message)
        if bool(hits) != bad:
            print(f"selftest missed {message!r}: {hits}", file=sys.stderr)
            return 1
    print("trailer selftest passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--base", default="")
    parser.add_argument("--head", default="")
    args = parser.parse_args()
    if args.selftest:
        if selftest() != 0:
            return 1
        if not args.base:
            return 0
    if not args.base or not args.head:
        print("need --base and --head", file=sys.stderr)
        return 1
    failed = 0
    for sha, body in commits(args.base, args.head):
        for line in offending(body):
            print(f"{sha}: {line}", file=sys.stderr)
            failed += 1
    if failed:
        return 1
    print("no AI-attribution trailer in the range")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
