def fp_len(p):
    return (p.bit_length() + 7) // 8


def hex_fp2(value, p):
    """The verifier's canonical encoding: the real part, then the
    imaginary part, each little-endian in the bytes of `p`."""
    return (value[0].to_bytes(fp_len(p), "little") + value[1].to_bytes(fp_len(p), "little")).hex()


def hex_le(value, bits):
    return value.to_bytes((bits + 7) // 8, "little").hex()


def hex_matrix(M, e):
    return " ".join(hex_le(entry, e) for entry in M)


def secret_norm(e):
    """Item 33, ruled R1: the next prime after `2^(2 * WIDTH_BITS)`."""
    return next_prime(1 << (2 * width_bits(e)))


