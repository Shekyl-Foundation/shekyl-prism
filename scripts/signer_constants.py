# ---------------------------------------------------------------------------
# Fields. An element of F_{p^2} is a pair (a, b) for a + b*i, i^2 = -1, with
# a and b integers in [0, p). Python compares such pairs lexicographically,
# which is the order of 1.4.1 step 1.
# ---------------------------------------------------------------------------


class Fp2:
    """`F_p(i)`, `i^2 = -1`, for a prime `p` that is 3 modulo 4."""

    def __init__(self, p):
        assert p % 4 == 3
        self.p = p
        self.zero = (0, 0)
        self.one = (1, 0)
        self.i = (0, 1)

    def add(self, a, b):
        return ((a[0] + b[0]) % self.p, (a[1] + b[1]) % self.p)

    def sub(self, a, b):
        return ((a[0] - b[0]) % self.p, (a[1] - b[1]) % self.p)

    def neg(self, a):
        return (-a[0] % self.p, -a[1] % self.p)

    def mul(self, a, b):
        return ((a[0] * b[0] - a[1] * b[1]) % self.p, (a[0] * b[1] + a[1] * b[0]) % self.p)

    def inv(self, a):
        norm = pow(a[0] * a[0] + a[1] * a[1], -1, self.p)
        return (a[0] * norm % self.p, -a[1] * norm % self.p)

    def conj(self, a):
        return (a[0], -a[1] % self.p)

    def small(self, n):
        return (n % self.p, 0)

    def power(self, a, exponent):
        result = self.one
        while exponent:
            if exponent & 1:
                result = self.mul(result, a)
            a = self.mul(a, a)
            exponent >>= 1
        return result

    def is_square(self, a):
        norm = (a[0] * a[0] + a[1] * a[1]) % self.p
        return norm == 0 or pow(norm, (self.p - 1) // 2, self.p) == 1

    def sqrt(self, a):
        """A square root of a square. Which of the two is not specified;
        every caller that needs one of them chooses it itself."""
        p = self.p
        if a[1] == 0:
            if pow(a[0], (p - 1) // 2, p) in (0, 1):
                root = (pow(a[0], (p + 1) // 4, p), 0)
            else:
                root = (0, pow(-a[0] % p, (p + 1) // 4, p))
        else:
            norm = (a[0] * a[0] + a[1] * a[1]) % p
            delta = pow(norm, (p + 1) // 4, p)
            half = pow(2, -1, p)
            t = (a[0] + delta) * half % p
            if pow(t, (p - 1) // 2, p) != 1:
                t = (a[0] - delta) * half % p
            x = pow(t, (p + 1) // 4, p)
            root = (x, a[1] * pow(2 * x, -1, p) % p)
        assert self.mul(root, root) == a, "sqrt of a non-square"
        return root


class Fp4:
    """`F_{p^2}(t)`, `t^2 = nu` for a non-square `nu` of `F_{p^2}`. An
    element is a pair (u, v) of `F_{p^2}` elements for u + v*t. Only the
    halves of 1.4.3 live here."""

    def __init__(self, base):
        self.base = base
        k = 1
        while base.is_square((k, 1)):
            k += 1
        self.nu = (k, 1)
        self.zero = (base.zero, base.zero)
        self.one = (base.one, base.zero)
        # t^p = t * nu^((p - 1) / 2).
        self.t_frobenius = base.power(self.nu, (base.p - 1) // 2)

    def lift(self, u):
        return (u, self.base.zero)

    def descend(self, a):
        assert a[1] == self.base.zero, "not in F_{p^2}"
        return a[0]

    def add(self, a, b):
        return (self.base.add(a[0], b[0]), self.base.add(a[1], b[1]))

    def sub(self, a, b):
        return (self.base.sub(a[0], b[0]), self.base.sub(a[1], b[1]))

    def neg(self, a):
        return (self.base.neg(a[0]), self.base.neg(a[1]))

    def mul(self, a, b):
        k = self.base
        return (
            k.add(k.mul(a[0], b[0]), k.mul(self.nu, k.mul(a[1], b[1]))),
            k.add(k.mul(a[0], b[1]), k.mul(a[1], b[0])),
        )

    def inv(self, a):
        k = self.base
        norm = k.inv(k.sub(k.mul(a[0], a[0]), k.mul(self.nu, k.mul(a[1], a[1]))))
        return (k.mul(a[0], norm), k.neg(k.mul(a[1], norm)))

    def small(self, n):
        return self.lift(self.base.small(n))

    def frobenius(self, a):
        """The `p`-power map."""
        k = self.base
        return (k.conj(a[0]), k.mul(k.conj(a[1]), self.t_frobenius))

    def sqrt_of_base(self, c):
        """A square root, here, of an element of `F_{p^2}`: every one has
        two."""
        k = self.base
        if k.is_square(c):
            return (k.sqrt(c), k.zero)
        return (k.zero, k.sqrt(k.mul(c, k.inv(self.nu))))


# ---------------------------------------------------------------------------
# The starting curve E0: y^2 = x^3 + x, over either field. A point is a pair
# (x, y), or None for the point at infinity.
# ---------------------------------------------------------------------------


def on_curve(K, P):
    return P is None or K.mul(P[1], P[1]) == K.add(K.mul(K.mul(P[0], P[0]), P[0]), P[0])


def negate(K, P):
    return None if P is None else (P[0], K.neg(P[1]))


def add(K, P, Q):
    if P is None:
        return Q
    if Q is None:
        return P
    if P[0] == Q[0]:
        if K.add(P[1], Q[1]) == K.zero:
            return None
        slope = K.mul(K.add(K.mul(K.small(3), K.mul(P[0], P[0])), K.one), K.inv(K.add(P[1], P[1])))
    else:
        slope = K.mul(K.sub(Q[1], P[1]), K.inv(K.sub(Q[0], P[0])))
    x = K.sub(K.sub(K.mul(slope, slope), P[0]), Q[0])
    return (x, K.sub(K.mul(slope, K.sub(P[0], x)), P[1]))


def multiply(K, scalar, P):
    assert scalar >= 0
    result = None
    while scalar:
        if scalar & 1:
            result = add(K, result, P)
        P = add(K, P, P)
        scalar >>= 1
    return result


def combine(K, a, P, b, Q):
    """`[a]P + [b]Q`."""
    return add(K, multiply(K, a, P), multiply(K, b, Q))


# ---------------------------------------------------------------------------
# 1.4.1: the starting basis, Algorithm B.1 of the SQIsign specification of
# 2026-09-01, steps numbered as in docs/SIGNER_SPEC.md.
# ---------------------------------------------------------------------------


def odd_divisors(f):
    return [d for d in range(1, f + 1) if f % d == 0]


def starting_basis(e, f):
    """`(P0, Q0, search, branch, odd_parts, other_reading)`.

    `search` lists every candidate `m` that gave a point of order divisible
    by `2^e`, with what became of it. `odd_parts` is the odd part of the
    order of each of those points before step 4 multiplied by it.
    `other_reading` is the basis the same search gives if step 4 multiplies
    by `f` in place of the odd part of the point's order; the two differ
    only when some `odd_parts` entry is less than `f`.
    """
    K = Fp2(f * (1 << e) - 1)
    half_order = 1 << (e - 1)
    search, odd_parts = [], []
    chosen, other = [], []
    m = 0
    while len(chosen) < 2:
        # Step 2.
        m += 1
        x = (1, m)
        rhs = K.add(K.mul(K.mul(x, x), x), x)
        if not K.is_square(rhs):
            REACHED.add("step 2: not a square")
            continue
        # Step 3: the smaller root in the order of step 1.
        y = K.sqrt(rhs)
        R = (x, min(y, K.neg(y)))
        # Step 4.
        if multiply(K, f * half_order, R) is None:
            REACHED.add("step 4: 2^e does not divide the order")
            continue
        odd = next(d for d in odd_divisors(f) if multiply(K, d << e, R) is None)
        if odd < f:
            REACHED.add("step 4: the order misses a prime of f")
        by_order, by_cofactor = multiply(K, odd, R), multiply(K, f, R)
        # Step 5.
        if not chosen:
            role = "P0"
        elif multiply(K, half_order, by_order) != multiply(K, half_order, chosen[0]):
            role = "Q0"
        else:
            role = "dependent"
            REACHED.add("step 5: a dependent candidate")
        search.append((m, role))
        odd_parts.append(odd)
        if role != "dependent":
            chosen.append(by_order)
            other.append(by_cofactor)
    P0, Q0, branch = step_six(K, e, *chosen)
    REACHED.add(f"step 6: branch {branch}")
    return K, P0, Q0, search, branch, odd_parts, step_six(K, e, *other)[:2]


def step_six(K, e, first, second):
    """Step 6 of 1.4.1 on the two points of step 5: the basis, and which
    of the three cases gave it.

    The first case is never taken by the search of steps 2 to 5 (1.4.1
    says why, and `--selftest` holds it at toy primes); it is kept because
    it is the rule as published, and the self-test calls it directly.
    """
    half_order = 1 << (e - 1)
    origin = (K.zero, K.zero)
    if multiply(K, half_order, second) == origin:
        return first, second, 1
    if multiply(K, half_order, first) == origin:
        return second, first, 2
    return first, add(K, second, first), 3


def squareness(K, m):
    """Which of `x - i`, `x`, `x + i` are squares for `x = 1 + m*i`, as a
    string of `S` and `N`. The norm of `1 + k*i` is `1 + k^2`, so this is
    three Legendre symbols."""
    return "".join("S" if K.is_square((1, k)) else "N" for k in (m - 1, m, m + 1))


# ---------------------------------------------------------------------------
# Discrete logarithms in E0[2^e] on the basis (P0, Q0).
# ---------------------------------------------------------------------------


class Basis:
    def __init__(self, K, e, P0, Q0):
        self.K, self.e, self.P0, self.Q0 = K, e, P0, Q0
        # [2^k]P0 and [2^k]Q0 for k < e.
        self.p_table, self.q_table = [P0], [Q0]
        for _ in range(e - 1):
            self.p_table.append(add(K, self.p_table[-1], self.p_table[-1]))
            self.q_table.append(add(K, self.q_table[-1], self.q_table[-1]))
        self.p_top, self.q_top = self.p_table[-1], self.q_table[-1]
        self.sum_top = add(K, self.p_top, self.q_top)

    def coordinates(self, S):
        """`(a, b)` in `[0, 2^e)` with `S = [a]P0 + [b]Q0`."""
        a, b = self._solve(S, 0, self.e)
        assert combine(self.K, a, self.P0, b, self.Q0) == S, "not in the span of the basis"
        return a, b

    def _solve(self, S, low, n):
        # S is [a][2^low]P0 + [b][2^low]Q0 with a, b below 2^n; low + n = e.
        K = self.K
        if S is None:
            return 0, 0
        if n == 1:
            if S == self.p_top:
                return 1, 0
            if S == self.q_top:
                return 0, 1
            assert S == self.sum_top, "not in the span of the basis"
            return 1, 1
        h = n // 2
        a0, b0 = self._solve(multiply(K, 1 << (n - h), S), low + n - h, h)
        rest = add(K, S, negate(K, combine(K, a0, self.p_table[low], b0, self.q_table[low])))
        a1, b1 = self._solve(rest, low + h, n - h)
        return a0 + (a1 << h), b0 + (b1 << h)

    def matrix(self, on_p, on_q):
        """The matrix of a map with these images: columns are images
        (1.4.2), returned as (m11, m12, m21, m22)."""
        a_p, b_p = self.coordinates(on_p)
        a_q, b_q = self.coordinates(on_q)
        return (a_p, a_q, b_p, b_q)

    def acts_as(self, M, on_p, on_q):
        """Whether `M` sends `P0` and `Q0` to these two points."""
        K = self.K
        return (
            combine(K, M[0], self.P0, M[2], self.Q0) == on_p
            and combine(K, M[1], self.P0, M[3], self.Q0) == on_q
        )


def mat_mul(A, B, modulus):
    return (
        (A[0] * B[0] + A[1] * B[2]) % modulus,
        (A[0] * B[1] + A[1] * B[3]) % modulus,
        (A[2] * B[0] + A[3] * B[2]) % modulus,
        (A[2] * B[1] + A[3] * B[3]) % modulus,
    )


def mat_add(A, B, modulus):
    return tuple((a + b) % modulus for a, b in zip(A, B))


def mat_scale(scalar, A, modulus):
    return tuple(scalar * a % modulus for a in A)


def identity(scalar, modulus):
    return (scalar % modulus, 0, 0, scalar % modulus)


def trace(A, modulus):
    return (A[0] + A[3]) % modulus


def determinant(A, modulus):
    return (A[0] * A[3] - A[1] * A[2]) % modulus


