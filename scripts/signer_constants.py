"""The signer's constants, generated from their definitions.

`docs/SIGNER_SPEC.md` section 1 says what each constant is. This script
computes them at the five parameter sets from that section's rules (1.4)
and writes them to `prism-vectors/data/signer/`: one file for each set,
and `shared.txt` for what does not depend on the prime.

    signer_constants.py --check       what CI runs: regenerate, compare byte
                                      for byte, compare with the oracles, and
                                      run every defining property
    signer_constants.py --write       rewrite the generated files
    signer_constants.py --selftest    the rules at toy primes, where every
                                      branch a search can reach is reached;
                                      the primality test's legs; the parsers
    signer_constants.py --extract-c [--write]
                                      re-extract the C reference's values from
                                      external/PRISM_v2 and compare with (or
                                      rewrite) oracle_c_reference.txt
    signer_constants.py --extract-sqisign-rs PATH [--write]
                                      the same for a checkout of sqisign-rs

Standard library only, Python 3.8 or later. The field arithmetic, the
order on the field, square roots, point arithmetic and discrete logarithms
are written here, so that no library's convention can enter a value.

Two things are kept apart. The generating functions (`generate`,
`shared_text`) read no oracle file and no file of another code base: they
take a prime and return text. The oracle files are read by `compare`
alone, which takes two tables and says where they differ. `--check` holds
that the generated bytes do not change when the oracle files are absent.

What is not a proof here: "prime" means a Baillie-PSW probable prime, by
the test `docs/VERIFIER_SPEC.md` specifies (departure D15). A candidate
below a "next prime" is refused only by a leg that never refuses a prime,
so "next" is exact if the result is prime. The nightly checks the five
results with sympy; a proof is ledger O19's.
"""
