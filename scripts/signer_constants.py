def parse_rows(text, name):
    """`{(set, row): value}` for an oracle file, or `{row: value}` for a
    generated one, with `#` lines dropped."""
    rows = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition(" ")
        if not separator:
            raise SystemExit(f"{name}:{number}: not `<name> <value>`")
        if key in rows:
            raise SystemExit(f"{name}:{number}: `{key}` twice")
        rows[key] = value
    return rows


def oracle_rows(text, name):
    """`{set: {row: value}}` for an oracle file, whose lines are
    `<set>.<row> <value>`."""
    by_set = {}
    for key, value in parse_rows(text, name).items():
        set_name, separator, row = key.partition(".")
        if not separator:
            raise SystemExit(f"{name}: `{key}` is not `<set>.<row>`")
        by_set.setdefault(set_name, {})[row] = value
    return by_set


