def rust_constants(path):
    """`{name: bytes}` for the byte arrays of a generated `sqisign-rs`
    file, and `{name: int}` for its integer constants."""
    found = {}
    text = path.read_text()
    for chunk in text.split("pub const ")[1:]:
        name = chunk.split(":")[0]
        _, separator, value = chunk.partition(" = ")
        if not separator:
            continue
        value = value.split(";")[0]
        if "[" in value:
            digits = value.replace("[", " ").replace("]", " ").replace(",", " ").split()
            found[name] = bytes(int(byte, 16) for byte in digits)
        elif value.strip().isdigit():
            found[name] = int(value)
    return found


