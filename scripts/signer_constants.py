# 1.4.2 and 1.4.3: the endomorphisms and their matrices.
# ---------------------------------------------------------------------------


def endo_i(K, i, P):
    """`(x, y) -> (-x, i*y)`, with `i` the field's own square root of -1."""
    return None if P is None else (K.neg(P[0]), K.mul(i, P[1]))


def frobenius2(K, P):
    """The `p`-power Frobenius on a point over `F_{p^2}`: conjugation."""
    return None if P is None else (K.conj(P[0]), K.conj(P[1]))


def halves(K, K4, P):
    """Two different points `H` over `F_{p^4}` with `2H = P`.

    `x^3 + x = x(x - i)(x + i)`. With `r1^2 = x`, `r2^2 = x - i`,
    `r3^2 = x + i`, a half has `x_H = x + r1 r2 + r2 r3 + r3 r1` and
    `y_H = +-(r1 + r2)(r2 + r3)(r3 + r1)`, whatever the signs of the three
    roots; the sign of `y_H` is the one for which the point doubles to `P`,
    found by trying, and the doubling is the test. Changing the signs of
    `r1` and `r2` together gives another half.
    """
    x, y = P
    roots = [K4.sqrt_of_base(x), K4.sqrt_of_base(K.sub(x, K.i)), K4.sqrt_of_base(K.add(x, K.i))]
    target = (K4.lift(x), K4.lift(y))

    def half(r1, r2, r3):
        pairs = K4.add(K4.add(K4.mul(r1, r2), K4.mul(r2, r3)), K4.mul(r3, r1))
        x_h = K4.add(K4.lift(x), pairs)
        y_h = K4.mul(K4.mul(K4.add(r1, r2), K4.add(r2, r3)), K4.add(r3, r1))
        found = [
            candidate
            for candidate in ((x_h, y_h), (x_h, K4.neg(y_h)))
            if on_curve(K4, candidate) and add(K4, candidate, candidate) == target
        ]
        assert len(found) == 1, "exactly one sign of y_H halves the point"
        return found[0]

    first = half(*roots)
    second = half(K4.neg(roots[0]), K4.neg(roots[1]), roots[2])
    assert first != second
    return first, second


def halved_images(K, K4, H):
    """`((i + pi)(H), (1 + k)(H))` for a half `H` of a point `R`, back in
    `F_{p^2}`: the images of `R` under `(i + j)/2` and `(1 + k)/2`."""
    i4 = K4.lift(K.i)

    def i_map(P):
        return (K4.neg(P[0]), K4.mul(i4, P[1]))

    def pi_map(P):
        return (K4.frobenius(P[0]), K4.frobenius(P[1]))

    # The maps on the extension satisfy the algebra's relations on this point.
    assert i_map(i_map(H)) == negate(K4, H), "i^2 = -1 over the extension"
    assert pi_map(pi_map(H)) == negate(K4, multiply(K4, K.p, H)), "pi^2 = -p over the extension"
    assert i_map(pi_map(H)) == negate(K4, pi_map(i_map(H))), "i pi = -pi i over the extension"

    def down(P):
        return None if P is None else (K4.descend(P[0]), K4.descend(P[1]))

    return down(add(K4, i_map(H), pi_map(H))), down(add(K4, H, i_map(pi_map(H))))


def actions(K, e, P0, Q0):
    """The six matrices and the checks of 1.4.2 and 1.4.3 on points."""
    modulus = 1 << e
    basis = Basis(K, e, P0, Q0)
    K4 = Fp4(K)
    i_p, i_q = endo_i(K, K.i, P0), endo_i(K, K.i, Q0)
    j_p, j_q = frobenius2(K, P0), frobenius2(K, Q0)
    k_p, k_q = endo_i(K, K.i, j_p), endo_i(K, K.i, j_q)
    m_i = basis.matrix(i_p, i_q)
    m_j = basis.matrix(j_p, j_q)
    m_k = basis.matrix(k_p, k_q)
    first_p, second_p = halves(K, K4, P0)
    first_q, second_q = halves(K, K4, Q0)
    gen3_p, gen4_p = halved_images(K, K4, first_p)
    gen3_q, gen4_q = halved_images(K, K4, first_q)
    # 1.4.3: the result does not depend on which half is taken.
    assert halved_images(K, K4, second_p) == (gen3_p, gen4_p), "the other half of P0 gives another image"
    assert halved_images(K, K4, second_q) == (gen3_q, gen4_q), "the other half of Q0 gives another image"
    gen3 = basis.matrix(gen3_p, gen3_q)
    gen4 = basis.matrix(gen4_p, gen4_q)
    matrices = {"i": m_i, "j": m_j, "k": m_k, "gen2": m_i, "gen3": gen3, "gen4": gen4}
    images = {
        "i": (i_p, i_q),
        "j": (j_p, j_q),
        "k": (k_p, k_q),
        "gen2": (i_p, i_q),
        "gen3": (gen3_p, gen3_q),
        "gen4": (gen4_p, gen4_q),
    }
    for name, M in matrices.items():
        assert basis.acts_as(M, *images[name]), f"the matrix of {name} is not its action"
    assert not identities_fail(matrices, K.p, modulus), identities_fail(matrices, K.p, modulus)
    return basis, matrices, images


def identities_fail(m, p, modulus):
    """The matrix identities of 1.4.2 that do not hold, by name."""
    checks = {
        "i^2 = -1": mat_mul(m["i"], m["i"], modulus) == identity(-1, modulus),
        "j^2 = -p": mat_mul(m["j"], m["j"], modulus) == identity(-p, modulus),
        "k = i j": mat_mul(m["i"], m["j"], modulus) == m["k"],
        "k = -j i": mat_scale(-1, mat_mul(m["j"], m["i"], modulus), modulus) == m["k"],
        "trace and determinant of i": (trace(m["i"], modulus), determinant(m["i"], modulus)) == (0, 1),
        "trace and determinant of j": (trace(m["j"], modulus), determinant(m["j"], modulus)) == (0, p % modulus),
        "gen2 = i": m["gen2"] == m["i"],
        **halved_identities(m, "gen3", p, modulus),
        **halved_identities(m, "gen4", p, modulus),
    }
    return sorted(name for name, holds in checks.items() if not holds)


def halved_identities(m, which, p, modulus, candidate=None):
    """The identities a matrix of `(i + j)/2` or `(1 + k)/2` satisfies:
    necessary, and not sufficient (1.4.3)."""
    M = m[which] if candidate is None else candidate
    quarter = (p + 1) // 4 % modulus
    if which == "gen3":
        return {
            "2 gen3 = i + j": mat_scale(2, M, modulus) == mat_add(m["i"], m["j"], modulus),
            "trace of gen3": trace(M, modulus) == 0,
            "determinant of gen3": determinant(M, modulus) == quarter,
            "gen3^2 = -(p + 1)/4": mat_mul(M, M, modulus) == identity(-quarter, modulus),
        }
    return {
        "2 gen4 = 1 + k": mat_scale(2, M, modulus) == mat_add(identity(1, modulus), m["k"], modulus),
        "trace of gen4": trace(M, modulus) == 1,
        "determinant of gen4": determinant(M, modulus) == quarter,
        "gen4^2 - gen4 + (p + 1)/4 = 0": mat_add(
            mat_mul(M, M, modulus), mat_scale(-1, M, modulus), modulus
        )
        == identity(-quarter, modulus),
    }


def top_bit_candidates(M, e):
    """The 16 matrices equal to `M` except, possibly, in the top bit of
    each entry: `M` itself first."""
    top = 1 << (e - 1)
    return [tuple(entry ^ (top if mask >> n & 1 else 0) for n, entry in enumerate(M)) for mask in range(16)]


def identities_pass_count(m, which, p, e):
    """How many of the 16 pass every identity of `halved_identities`."""
    modulus = 1 << e
    return sum(
        all(halved_identities(m, which, p, modulus, candidate).values())
        for candidate in top_bit_candidates(m[which], e)
    )


