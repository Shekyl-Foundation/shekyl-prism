def limb_integers(text, bits, expected):
    """Every big integer of a generated C file, read from the variant for
    limbs of `bits` bits."""
    values = []
    lines = text.splitlines()
    for number, line in enumerate(lines):
        if line.strip() != f"#elif GMP_LIMB_BITS == {bits}":
            continue
        body = lines[number + 1]
        size = int(body.split("._mp_size = ")[1].split(",")[0])
        limbs = [int(limb, 16) for limb in body.split("{")[-1].split("}")[0].split(",")]
        magnitude = sum(limb << (bits * k) for k, limb in enumerate(limbs[: abs(size)]))
        values.append(-magnitude if size < 0 else magnitude)
    if len(values) != expected:
        raise SystemExit(f"read {len(values)} integers at {bits} bits where {expected} were expected")
    return values


def c_integers(path, expected):
    """The integers of a file; its three limb widths must agree."""
    text = path.read_text()
    by_width = [limb_integers(text, bits, expected) for bits in (16, 32, 64)]
    if not by_width[0] == by_width[1] == by_width[2]:
        raise SystemExit(f"{path}: the three limb widths disagree")
    return by_width[2]


def c_field_elements(path, words, p, expected):
    """Every element of `F_p` of a generated C file, from its 64-bit
    Montgomery-form variant (`words` words, `R = 2^(64 * words)`)."""
    values = []
    lines = path.read_text().splitlines()
    unscale = pow(1 << (64 * words), -1, p)
    for number, line in enumerate(lines):
        if "SQISIGN_GF_IMPL_BROADWELL" not in line or not lines[number + 1].startswith("{0x"):
            continue
        limbs = [int(limb, 16) for limb in lines[number + 1].strip("{}, ").replace("}", "").split(",")]
        if len(limbs) != words:
            raise SystemExit(f"{path}:{number + 2}: {len(limbs)} words where {words} were expected")
        values.append(sum(limb << (64 * k) for k, limb in enumerate(limbs)) * unscale % p)
    if len(values) != expected:
        raise SystemExit(f"{path}: read {len(values)} field elements where {expected} were expected")
    return values


def c_define(text, name):
    for line in text.splitlines():
        words = line.split()
        if len(words) == 3 and words[:2] == ["#define", name]:
            return int(words[2])
    raise SystemExit(f"no #define {name}")


def c_line(text, prefix):
    found = [line for line in text.splitlines() if line.startswith(prefix)]
    if len(found) != 1:
        raise SystemExit(f"{len(found)} lines start with `{prefix}`")
    return found[0]


