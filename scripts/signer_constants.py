# Toy primes f * 2^e - 1 that are 3 modulo 4, as (e, f), and what each is
# here for. Between them every branch of 1.4.1 is taken.
TOY_PRIMES = (
    (3, 1, 3, "p = 7: step 2 refuses a candidate"),
    (3, 9, 3, "p = 71: step 4 refuses a point whose order 2^e does not divide"),
    (3, 25, 2, "p = 199: the exchange"),
    (4, 5, 2, "p = 79: a dependent candidate, then the exchange"),
    (3, 33, 3, "p = 263: each order misses a prime of f (11 of 33)"),
    (3, 91, 3, "p = 727: one order misses a prime of f (13 of 91)"),
    (4, 57, 2, "p = 911: a dependent candidate, and an order that misses a prime of f"),
    (11, 3, 3, "p = 6143: eleven levels of the discrete logarithm"),
)
# The sweep that holds that step 6 never takes its first case: every prime
# f * 2^e - 1 with e and f in these ranges.
SWEEP_E = range(2, 8)
SWEEP_F = range(1, 64, 2)
EVERY_BRANCH = {
    "step 2: not a square",
    "step 4: 2^e does not divide the order",
    "step 4: the order misses a prime of f",
    "step 5: a dependent candidate",
    "step 6: branch 1",
    "step 6: branch 2",
    "step 6: branch 3",
}


def toy(e, f):
    """The rules at one toy prime, with every property that does not need
    an oracle. Returns what the search did."""
    K, P0, Q0, search, branch, odd_parts, other_reading = starting_basis(e, f)
    assert baillie_psw(K.p)[0] == "prime" and K.p % 4 == 3
    half_order = 1 << (e - 1)
    for point in (P0, Q0):
        assert on_curve(K, point)
        assert multiply(K, half_order, point) is not None and multiply(K, 1 << e, point) is None
    assert multiply(K, half_order, P0) != multiply(K, half_order, Q0)
    assert multiply(K, half_order, Q0) == (K.zero, K.zero)
    basis, matrices, images = actions(K, e, P0, Q0)
    for which, M in matrices.items():
        assert basis.acts_as(M, *images[which])
        for candidate in top_bit_candidates(M, e)[1:]:
            assert not basis.acts_as(candidate, *images[which]), "a wrong matrix acts as the map"
    return search, branch, odd_parts, other_reading != (P0, Q0)


def sweep():
    """Step 6 at every prime of the sweep: never its first case, and the
    case is the one the squareness of the first point's `x` decides
    (1.4.1). Returns how many primes took each case."""
    taken = {2: 0, 3: 0}
    for e in SWEEP_E:
        for f in SWEEP_F:
            p = f * (1 << e) - 1
            if baillie_psw(p)[0] != "prime":
                continue
            K, P0, Q0, search, branch, _, _ = starting_basis(e, f)
            first = squareness(K, search[0][0])
            assert first in ("SNN", "NSN"), (e, f, first)
            assert branch == (2 if first == "NSN" else 3), (e, f, first, branch)
            if branch == 3:
                assert len(search) == 2 and squareness(K, search[1][0]) == "NNS", (e, f, search)
            taken[branch] += 1
    return taken


def selftest():
    REACHED.clear()
    seen = []
    for e, f, expected_branch, purpose in TOY_PRIMES:
        search, branch, odd_parts, readings_differ = toy(e, f)
        assert branch == expected_branch, (e, f, branch)
        if "misses a prime" in purpose:
            assert min(odd_parts) < f, (e, f, odd_parts)
            # Otherwise the case shows nothing: here the two readings of
            # step 4 give different points.
            assert readings_differ, (e, f)
        if "dependent" in purpose:
            assert any(role == "dependent" for _, role in search), (e, f, search)
        seen.append((e, f, branch))
    assert REACHED == EVERY_BRANCH - {"step 6: branch 1"}, sorted(REACHED ^ EVERY_BRANCH)
    swept = sweep()
    # Step 6's first case, which no search reaches: called on the two points
    # of an exchange in the other order. The same basis comes out.
    K, P0, Q0 = starting_basis(3, 25)[:3]
    assert step_six(K, 3, P0, Q0) == (P0, Q0, 1)
    # The two legs of the primality test, each on pseudoprimes of the other.
    for n in (2047, 3277, 4033, 4681, 8321):
        assert strong_base_two(n) and strong_lucas(n) == "composite", n
    for n in (5459, 5777, 10877, 16109, 18971):
        assert strong_lucas(n) == "pass" and not strong_base_two(n), n
    for n in (101, 103, 1237, 2**61 - 1, 2**127 - 1):
        assert baillie_psw(n) == ("prime", None), n
    for n, leg in ((25, "sieve"), (10403, "base 2"), ((1 << 512) + 1, "lucas")):
        assert baillie_psw(n) == ("composite", leg), (n, baillie_psw(n))
    # A square has no discriminant with symbol -1: refused, and not as a proof.
    assert strong_lucas(1194649) == "no discriminant"
    assert next_prime(1 << 16)[0] == 65537 and next_prime(89)[0] == 97
    assert jacobi(2, 7) == 1 and jacobi(3, 7) == -1 and jacobi(21, 7) == 0
    # The comparison refuses a value that differs, a row that is missing,
    # and a table that is empty.
    ours = {"basis_px": "00", "basis_qx": "01"}
    assert compare(ours, dict(ours), ("basis_px", "basis_qx")) == []
    assert compare(ours, {**ours, "basis_qx": "02"}, ("basis_px", "basis_qx")) == ["basis_qx"]
    assert compare(ours, {"basis_px": "00"}, ("basis_px", "basis_qx")) == ["basis_qx"]
    assert compare(ours, {}, ("basis_px", "basis_qx")) == ["basis_px", "basis_qx"]
    # The parsers refuse what they cannot read.
    for bad in ("norow\n", "a 1\na 2\n"):
        try:
            parse_rows(bad, "selftest")
        except SystemExit:
            pass
        else:
            raise AssertionError(f"read {bad!r}")
    limbs = "#elif GMP_LIMB_BITS == 64\n{{._mp_alloc = 0, ._mp_size = %d, ._mp_d = (mp_limb_t[]) {%s}}}\n"
    try:
        limb_integers(limbs % (1, "0x5"), 64, 2)
    except SystemExit:
        pass
    else:
        raise AssertionError("a file with one integer was read as two")
    assert limb_integers(limbs % (-2, "0x5,0x1"), 64, 1) == [-(5 + (1 << 64))]
    # The encodings do not depend on the machine.
    assert hex_le(0x0102, 16) == "0201" and hex_le(1, 9) == "0100"
    assert hex_fp2((1, 2), 0xFFFF) == "01000200"
    assert shared_text().endswith("\n") and "\r" not in shared_text()
    # The generating path reads nothing of the oracles: with the data
    # directory out of reach it writes the same bytes.
    global OUT, ORACLE_C, ORACLE_R
    expected = committed("p248.txt"), committed("shared.txt")
    saved = OUT, ORACLE_C, ORACLE_R
    OUT = ORACLE_C = ORACLE_R = ROOT / "no-such-directory"
    try:
        assert committed("p248.txt") is None
        assert (set_text(compute("p248", 248, 5)), shared_text()) == expected
    finally:
        OUT, ORACLE_C, ORACLE_R = saved
    # A corrupted oracle value fails the comparison against what is
    # committed, in memory and with nothing written.
    c_text, r_text = committed(ORACLE_C.name), committed(ORACLE_R.name)
    for set_name, oracle_text, oracle_name, rows in (
        ("p248", c_text, ORACLE_C.name, COMPARED_WITH_C),
        ("p664", r_text, ORACLE_R.name, COMPARED_WITH_R),
    ):
        ours = parse_rows(committed(f"{set_name}.txt"), set_name)
        theirs = oracle_rows(oracle_text, oracle_name)[set_name]
        assert compare(ours, theirs, rows) == []
        for row in rows:
            value = theirs[row]
            flipped = value[:-1] + ("0" if value[-1] != "0" else "1")
            assert compare(ours, {**theirs, row: flipped}, rows) == [row], (set_name, row)
    print(
        f"signer constants self-test: {len(seen)} toy primes reach every branch a search can reach; "
        f"step 6 takes its second case at {swept[2]} and its third at {swept[3]} of {swept[2] + swept[3]} "
        "swept primes and its first at none; the primality legs, the comparison and the parsers "
        "refuse what they must"
    )
    return 0


def main(argv):
    rewrite = "--write" in argv
    arguments = [argument for argument in argv if argument != "--write"]
    if arguments == ["--selftest"] and not rewrite:
        return selftest()
    if arguments in ([], ["--check"]) and (rewrite or arguments):
        return check(rewrite)
    if arguments == ["--extract-c"]:
        return extract(extract_c(ROOT / "external" / "PRISM_v2"), ORACLE_C, rewrite)
    if len(arguments) == 2 and arguments[0] == "--extract-sqisign-rs":
        return extract(extract_sqisign_rs(Path(arguments[1]).resolve()), ORACLE_R, rewrite)
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
